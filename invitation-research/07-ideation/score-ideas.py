#!/usr/bin/env python3
"""Rank 07-ideation/ideas.csv (brief 03 §16).

    python3 -B invitation-research/07-ideation/score-ideas.py            # print the ranking, write ranking.md
    python3 -B invitation-research/07-ideation/score-ideas.py --check    # validate only

Every axis is 1-5 and oriented so that HIGHER IS BETTER:
  impact      5 = removes a top user problem for many hosts or guests
  uniqueness  5 = not seen at any Tier-A competitor
  feasibility 5 = fits the current stack and data model without new vendors
  effort      5 = smallest effort (S), 1 = largest (L+)            (inverted on purpose)
  risk        5 = lowest risk to published invitations, money, privacy or policy
score = 2 x impact + uniqueness + feasibility + effort + risk  (max 30)
Ties: higher impact, then observed demand before proposed, then uniqueness, then idea_id.
"""
import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AXES = ('impact', 'uniqueness', 'feasibility', 'effort', 'risk')


def load():
    with open(os.path.join(HERE, 'ideas.csv'), newline='', encoding='utf-8') as handle:
        return list(csv.DictReader(handle))


def validate(ideas):
    errors = []
    seen = set()
    for idea in ideas:
        iid = idea['idea_id']
        if iid in seen:
            errors.append(f'{iid}: duplicate')
        seen.add(iid)
        if idea['demand'] not in ('observed', 'proposed'):
            errors.append(f'{iid}: demand must be observed or proposed')
        if idea['demand'] == 'observed' and not idea['evidence']:
            errors.append(f'{iid}: observed demand needs evidence IDs')
        for axis in AXES:
            if idea[axis] not in ('1', '2', '3', '4', '5'):
                errors.append(f'{iid}: {axis}={idea[axis]!r} not in 1-5')
    if len(ideas) < 25:
        errors.append(f'{len(ideas)} ideas; brief 03 §16 requires at least 25')
    return errors


def score(idea):
    return 2 * int(idea['impact']) + sum(int(idea[a]) for a in AXES[1:])


def ranked(ideas):
    return sorted(ideas, key=lambda i: (-score(i), -int(i['impact']), i['demand'] != 'observed', -int(i['uniqueness']), i['idea_id']))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    ideas = load()
    errors = validate(ideas)
    for error in errors:
        print(f'ERROR {error}')
    if errors:
        return 1
    order = ranked(ideas)
    lines = ['<!-- generated by score-ideas.py; do not edit by hand -->', '# ranking.md: ideas ranked by score', '',
             'score = 2 × impact + uniqueness + feasibility + effort + risk (all 1–5, higher is better; effort and risk inverted).', '',
             '| Rank | Idea | Demand | Impact | Uniq. | Feas. | Effort | Risk | Score |', '|---|---|---|---|---|---|---|---|---|']
    for rank, idea in enumerate(order, start=1):
        lines.append(f"| {rank} | {idea['idea_id']} {idea['title']} | {idea['demand']} | {idea['impact']} | {idea['uniqueness']} | "
                     f"{idea['feasibility']} | {idea['effort']} | {idea['risk']} | **{score(idea)}** |")
        print(f"{rank:2d}. {idea['idea_id']} {score(idea):2d} [{idea['demand']}] {idea['title']}")
    observed = sum(1 for i in ideas if i['demand'] == 'observed')
    lines += ['', f'{len(ideas)} ideas: {observed} with observed demand (evidence IDs in `ideas.csv`), {len(ideas) - observed} proposed.', '']
    if not args.check:
        with open(os.path.join(HERE, 'ranking.md'), 'w', encoding='utf-8') as handle:
            handle.write('\n'.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
