#!/usr/bin/env python3
"""Summarize spike results (k6 --summary-export JSON + sample-proc.py JSON) into results/summary.md.

    python3 -B invitation-research/08-backend-rust-plan/spike/summarize-spike.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, 'results')
SCENARIOS = (('read-spike', 'Read spike: 0→40 VUs, 40 VUs for 40 s, →0 (closed model, no think time)'),
             ('rsvp-burst', 'RSVP write burst: 0→20 VUs, 20 VUs for 30 s, →0 (POST, redirects not followed)'),
             ('fixed-read', 'Equal-load read: 10 requests/s for 30 s (open model)'))
TARGETS = (('next', 'Next.js (current, production build)'), ('rust', 'Rust Axum spike'))


def load(name):
    path = os.path.join(RESULTS, name)
    if not os.path.exists(path):
        return None
    with open(path) as handle:
        return json.load(handle)


def metric(k6, name, field):
    values = (k6.get('metrics') or {}).get(name) or {}
    return values.get(field, values.get('values', {}).get(field) if isinstance(values.get('values'), dict) else None)


def row(target, scenario):
    k6 = load(f'{target}-{scenario}-k6.json')
    proc = load(f'{target}-{scenario}-proc.json')
    if not k6:
        return None
    reqs = metric(k6, 'http_reqs', 'count') or 0
    rate = metric(k6, 'http_reqs', 'rate') or 0
    failed = metric(k6, 'http_req_failed', 'value')
    checks = (k6.get('metrics') or {}).get('checks') or {}
    passes, fails = checks.get('passes', 0), checks.get('fails', 0)
    duration = lambda f: metric(k6, 'http_req_duration', f)  # noqa: E731
    server = (proc or {}).get('summary', {}).get('server', {})
    postgres = (proc or {}).get('summary', {}).get('postgres', {})
    platform = (proc or {}).get('summary', {}).get('platform-dev', {})
    return {
        'reqs': int(reqs), 'rate': rate, 'failed': failed, 'checks': f'{passes}/{passes + fails}',
        'med': duration('med'), 'p90': duration('p(90)'), 'p95': duration('p(95)'), 'p99': duration('p(99)'), 'max': duration('max'),
        'cpu_mean': server.get('cpu_mean'), 'cpu_max': server.get('cpu_max'), 'rss_max': server.get('rss_max_mb'),
        'pg_cpu': postgres.get('cpu_mean'), 'platform_cpu': platform.get('cpu_mean'),
    }


def fmt(value, digits=1):
    return '–' if value is None else f'{value:,.{digits}f}'


def main():
    lines = ['<!-- generated by summarize-spike.py from results/*.json; do not edit by hand -->',
             '# Spike results summary', '',
             'Latency = k6 `http_req_duration` (ms). CPU = % of one core (2 vCPUs total), mean over the run, from /proc deltas. '
             'RSS = max MB of the server process group. "platform" = the hosting platform\'s `next dev` running on the same host '
             '(background load we could not stop).', '']
    for scenario, title in SCENARIOS:
        lines += [f'## {title}', '',
                  '| Target | Requests | Req/s | Failed rate | Checks | p50 | p90 | p95 | p99 | max | Server CPU mean / max % | Server RSS max MB | Postgres CPU % | Platform CPU % |',
                  '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
        for target, label in TARGETS:
            data = row(target, scenario)
            if not data:
                lines.append(f'| {label} | not run | | | | | | | | | | | | |')
                continue
            lines.append(f"| {label} | {data['reqs']:,} | {fmt(data['rate'])} | {fmt((data['failed'] or 0) * 100, 2)} % | {data['checks']} | "
                         f"{fmt(data['med'])} | {fmt(data['p90'])} | {fmt(data['p95'])} | {fmt(data['p99'])} | {fmt(data['max'])} | "
                         f"{fmt(data['cpu_mean'])} / {fmt(data['cpu_max'])} | {fmt(data['rss_max'])} | {fmt(data['pg_cpu'])} | {fmt(data['platform_cpu'])} |")
        lines.append('')
    with open(os.path.join(RESULTS, 'summary.md'), 'w') as handle:
        handle.write('\n'.join(lines))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
