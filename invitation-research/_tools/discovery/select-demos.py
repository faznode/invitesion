#!/usr/bin/env python3
"""Build the Phase 3/4 capture queue from raw/<competitor>/discovery-<CODE>.json.

    python3 invitation-research/_tools/discovery/select-demos.py [--per 6]
    -> invitation-research/04-template-benchmarks/queues/queue-tier-a.tsv  (id<TAB>competitor<TAB>demo<TAB>url)

Privacy rule (R1): only URL shapes that are clearly the vendor's OFFICIAL theme demos are eligible.
Pages that showcase customers' real invitations (e.g. Indoinvite /hasil/...?contoh) are never queued.
Competitors without an OFFICIAL pattern are reported as "needs manual pattern" instead of guessed.
Diversity: one pick per niche keyword group first, then evenly spaced picks across catalog order.
"""
import argparse
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RESEARCH = os.path.normpath(os.path.join(HERE, '..', '..'))

OFFICIAL = {
    'ENV': r'^https://enviory\.com/tema/[^/]+/pratinjau/?$',
    'IDI': r'^https://indoinvite\.com/preview/[^/?#]+/?$',
    'INV': r'^https://invi\.id/tema/[^/]+/\?to=',
    'IVT': r'^https://invitato\.net/template-[^/]+/\?code=DUMMY',
    # Couple-name subdomains linked from katsudoto.id/desain; verified as vendor placeholders (S-KAT-001).
    'KAT': r'^https://[a-z0-9-]+\.katsudoto\.id/\d+/?$',
    'VID': r'^https://(studio\.)?viding\.co/theme/preview/\d+/?$',
    'WEV': r'^https://www\.wevitation\.com/demo/[^/?#]+/?$',
}
PRIVATE_LOOKING = re.compile(r'(/hasil/|[?&]contoh|wp-content|\.(jpe?g|png|webp|gif|mp3|mp4|pdf)(\?|$))', re.I)
NICHES = [
    ('wedding', r'nikah|wedding|pernikahan|akad|resepsi|walimah'),
    ('regional', r'adat|jawa|sunda|bali|batak|minang|bugis|betawi|dayak|toraja'),
    ('islamic', r'islam|muslim|syar|arab|ramadan|lebaran'),
    ('khitan-aqiqah', r'khitan|sunat|aqiqah|tasmiyah'),
    ('birthday', r'ulang-?tahun|birthday|ultah|sweet'),
    ('premium', r'premium|exclusive|eksklusif|signature|luxury|gold|royal|3d|cinematic|video'),
    ('other-life', r'syukuran|tasyakuran|wisuda|graduation|baby|reuni|tahlil'),
]


def candidates(d):
    links = [x.get('href', '') for x in (d.get('demos') or [])] + list(d.get('catalogCandidates') or [])
    seen, out = set(), []
    for h in links:
        key = h.rstrip('/')
        if h and key not in seen:
            seen.add(key)
            out.append(h)
    return out


def pick(urls, per):
    chosen = []
    for _, rx in NICHES:
        for u in urls:
            if u not in chosen and re.search(rx, u, re.I):
                chosen.append(u)
                break
        if len(chosen) >= per:
            return chosen[:per]
    rest = [u for u in urls if u not in chosen]
    need = per - len(chosen)
    if rest and need > 0:
        step = max(1, len(rest) // need)
        chosen += rest[::step][:need]
    return chosen[:per]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--per', type=int, default=6)
    ap.add_argument('--out', default=os.path.join(RESEARCH, '04-template-benchmarks', 'queues', 'queue-tier-a.tsv'))
    ap.add_argument('--only', default='', help='comma-separated codes, e.g. KAT,RSV (default: all)')
    a = ap.parse_args()
    only = {c.strip().upper() for c in a.only.split(',') if c.strip()}
    rows, report = [], []
    for f in sorted(glob.glob(os.path.join(RESEARCH, 'raw', '*', 'discovery-*.json'))):
        d = json.load(open(f))
        code, comp = d['code'], d['competitor']
        if only and code not in only:
            continue
        pattern = OFFICIAL.get(code)
        if not pattern:
            report.append(f'# {code} {comp}: needs manual OFFICIAL pattern ({len(candidates(d))} raw links) — not queued')
            continue
        urls = [u for u in candidates(d) if re.search(pattern, u) and not PRIVATE_LOOKING.search(u)]
        picks = pick(urls, a.per)
        report.append(f'# {code} {comp}: {len(urls)} official demos found, {len(picks)} queued')
        for i, u in enumerate(picks, start=101):
            rows.append(f'C-{code}-{i}\t{comp}\tdemo\t{u}')
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w') as fh:
        fh.write('# queue-tier-a.tsv — generated by _tools/discovery/select-demos.py; regenerate, do not hand-edit picks\n')
        fh.write('# columns: id<TAB>competitor<TAB>kind<TAB>url — consumed by _tools/capture/run-batch.sh\n')
        fh.write('\n'.join(report) + '\n')
        fh.write('\n'.join(rows) + '\n')
    print('\n'.join(report))
    print(f'queued {len(rows)} -> {os.path.relpath(a.out, RESEARCH)}')


if __name__ == '__main__':
    main()
