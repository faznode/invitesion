#!/usr/bin/env python3
"""Visitor-style public page reads for competitor profiles (analysis script, not product code).

For each target: robots.txt first, then the homepage, then at most MAX_FOLLOW same-origin pricing / features /
catalog-index pages linked from it. One request at a time, >= SPACING_S between requests to one origin, no retries,
no forms, no login. A bot challenge or a 401/403/429/503 answer stops every further request to that origin; there is
no fallback client, reader or route (LATEST.md §6).

robots.txt policy (RFC 9309, with the project's conservative additions):
  * fetch outcome (D-022): 2xx = rules, 4xx = no rules, 5xx / 429 / unreachable = disallow everything. robots.txt
    redirects are followed for at most MAX_REDIRECTS hops (each hop paced against its own origin) and the rules apply
    to the initial authority; more hops count as unreachable.
  * matching: only `User-agent: *` groups apply to our generic browser UA (groups naming the same agent are
    combined); patterns match path + query after percent-encoding normalisation; `*` matches any sequence and a
    trailing `$` anchors the end; the longest pattern wins and an Allow wins a tie; `/robots.txt` is always allowed.
  * D-030 (s12, replaces D-026's blanket cross-agent reading): AI-agent groups bind by the identity and purpose of
    these reads (an Anthropic Claude agent retrieving pages at the owner's direction; no training, no search index),
    whatever User-Agent the tool sends:
      - applicable: `Claude-User` (Anthropic: Claude retrieving content at a user's direction), a `Content-Signal`
        with `ai-input=no` or `use=immediate` in a group that binds us (contentsignals.org, Cloudflare; RFC 9309
        §2.2.4 lets crawlers read such records), and a Cloudflare-managed Agent-policy section. A disallow is an
        opt-out: no request, origin stopped.
      - uncertain, restricted: the deprecated Anthropic names `anthropic-ai` / `Claude-Web`. Anthropic said in 2024
        that ClaudeBot honours directives set for them; its current documentation does not say whether Claude-User
        does. Until that is documented the restriction is kept (Q-O08) and labelled as such. Exception with a
        documented purpose: a legacy-token group inside the "Training crawlers" section of a Cloudflare Managed
        content block was generated by the site's Training = Disallow policy, so it is a training opt-out (recorded).
      - recorded, not binding: training or search tokens (ClaudeBot, Claude-SearchBot, GPTBot, CCBot, ...) and other
        operators' agents (ChatGPT-User, Perplexity-User, ExaUser, ...).
    The same matcher is used for every group, so `Disallow: /*` and path-specific rules count.
Redirects of page reads are never followed automatically: every hop is treated like a first request (origin not
stopped, robots.txt of that origin read first, path allowed, D-030, pacing) and a hop that lands on a demo / customer /
auth page (NEVER_REACH, D-008) is not requested.

Demo, preview, sample and customer pages are never followed: a vendor-linked "contoh" page can be a real
customer's event (D-008, S-IDI-003).

The committed output holds facts only (status, sizes, title, lang, price figures, counts, stack hints,
feature-keyword flags, app-store ids, internal path names). Page text goes to the private directory for
the analyst and is never committed.

  python3 -B profile-reads.py targets.tsv --out ../../raw/_discovery/profile-reads-YYYY-MM-DD.jsonl \
      --private-dir "$INVITESION_PRIVATE_DIR/profile-reads"
  python3 -B test_profile_reads.py          # offline regression tests (no network)
targets.tsv: "code<TAB>name<TAB>homepage-url[<TAB>extra-url ...]" (extra URLs are read as given, same rules).
"""
