def visible_text(page):
    t = TAG_STRIP.sub(" ", page)
    t = re.sub(r"<(br|/p|/div|/li|/h[1-6]|/tr|/section|/header|/footer)\b[^>]*>", "\n", t, flags=re.I)
    t = html.unescape(re.sub(r"<[^>]+>", " ", t))
    t = re.sub(r"[ \t\u00a0]+", " ", t)
    return PII.sub("[pii]", re.sub(r"\n\s*\n+", "\n", t)).strip()


def facts(url, final, page, origin):
    title = re.search(r"<title[^>]*>(.*?)</title>", page, re.I | re.S)
    lang = re.search(r"<html[^>]*\blang=[\"']?([\w-]+)", page, re.I)
    gen = re.search(r"<meta[^>]+name=[\"']generator[\"'][^>]+content=[\"']([^\"']+)", page, re.I)
    text = visible_text(page)
    links = re.findall(r"<a\b[^>]*href=[\"']([^\"'#]+)[\"'][^>]*>(.*?)</a>", page, re.I | re.S)
    internal, follow = [], []
    for href, label in links:
        absu = urllib.parse.urljoin(final, html.unescape(href.strip()))
        parts = urllib.parse.urlsplit(absu)
        if f"{parts.scheme}://{parts.netloc}" != origin:
            continue
        path = parts.path or "/"
        if path not in internal:
            internal.append(path)
        lab = re.sub(r"<[^>]+>", " ", label)
        candidate = path + ("?" if parts.query else "")
        if (FOLLOW_OK.search(path) or FOLLOW_OK.search(lab)) and not (NEVER_REACH.search(candidate) or NOT_FOLLOWED.search(candidate)):
            u = f"{origin}{path}"
            if u not in follow and u.rstrip("/") != final.rstrip("/"):
                follow.append(u)
    apps = sorted(set(re.findall(r"play\.google\.com/store/apps/details\?id=([\w.]+)", page)) |
                  set(re.findall(r"apps\.apple\.com/[\w/-]*?/app/[\w-]*/?(id\d+)", page)))
    return {
        "url": url, "final_url": final, "title": (html.unescape(title.group(1)).strip()[:140] if title else None),
        "lang": lang.group(1) if lang else None, "generator": gen.group(1)[:80] if gen else None,
        "bytes": len(page.encode()), "text_chars": len(text),
        "prices": sorted(set(p.strip() for p in PRICE.findall(text)))[:40],
        "counts": sorted(set(" ".join(c) for c in COUNT.findall(text)))[:12],
        "claims": sorted(set(" ".join(c) for c in CLAIM.findall(text)))[:12],
        "stack": sorted(k for k, rx in STACK.items() if re.search(rx, page, re.I)),
        "features": sorted(k for k, rx in FEATURES.items() if re.search(rx, text, re.I)),
        "app_ids": apps, "internal_paths": internal[:60],
        "api_markers": sorted(set(re.findall(r"(/wp-json/[\w/-]*|/api/[\w/.-]{1,40}|graphql|firebaseio\.com|"
                                             r"supabase\.co|algolia|/_next/data)", page)))[:20],
    }, follow, text


def read_target(reader, code, name, urls, private_dir, follow_links=True):
    """One target row → one JSONL record (facts only); page text goes to `private_dir/<code>/`."""
    rec = {"code": code, "name": name, "observed_at_utc": now_utc(),
           "method": "profile-reads.py (Android UA, plain GET, manual redirects)", "pages": [], "robots": {}}
    queue, seen, followed = list(urls), set(), 0
    pdir = os.path.join(private_dir, code)
    os.makedirs(pdir, exist_ok=True)
    while queue:
        url = queue.pop(0)
        if url in seen:
            continue
        seen.add(url)
        res = reader.get(url)
        for origin in {origin_of(url)} | {origin_of(h["location"]) for h in res["hops"]}:
            st = reader.origins.get(origin)
            if st and st.robots:
                rec["robots"][origin] = st.robots
                if st.recorded:
                    rec.setdefault("ai_groups_not_binding", {})[origin] = st.recorded
                if st.robots_text and not os.path.exists(os.path.join(pdir, f"robots-{urllib.parse.urlsplit(origin).netloc}.txt")):
                    with open(os.path.join(pdir, f"robots-{urllib.parse.urlsplit(origin).netloc}.txt"), "w", encoding="utf-8") as rf:
                        rf.write(st.robots_text)
        entry = {"url": url, "at_utc": now_utc()}
        if res["hops"]:
            entry["redirects"] = res["hops"]
        if "skipped" in res:
            entry["skipped"] = res["skipped"]
            rec["pages"].append(entry)
            continue
        entry.update(status=res["status"], content_type=(res["content_type"].split(";")[0] or None))
        if "error" in res:
            entry["error"] = res["error"]
        if "blocked" in res:
            entry["blocked"] = res["blocked"]
        if "error" in res or "blocked" in res or "html" not in res["content_type"].lower():
            rec["pages"].append(entry)
            continue
        page, final = res["body"].decode("utf-8", "replace"), res["final_url"]
        f, follow, text = facts(url, final, page, origin_of(final))
        entry.update(f)
        rec["pages"].append(entry)
        with open(os.path.join(pdir, f"{len(rec['pages']):02d}.txt"), "w", encoding="utf-8") as pf:
            pf.write(f"{url}\nstatus {res['status']}\n\n{text}\n")
        if follow_links and url == urls[0]:
            for u in follow:
                if followed < MAX_FOLLOW and u not in seen:
                    queue.append(u)
                    followed += 1
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("targets")
    ap.add_argument("--out", required=True)
    ap.add_argument("--private-dir", required=True)
    ap.add_argument("--no-follow", action="store_true")
    ap.add_argument("--accept-encoding", default=None,
                    help='send this Accept-Encoding (e.g. "gzip, deflate"); content negotiation, not a different client')
    a = ap.parse_args()
    reader = Reader(HttpTransport(accept_encoding=a.accept_encoding))
    with open(a.targets, encoding="utf-8") as fh, open(a.out, "a", encoding="utf-8") as out:
        for line in fh:
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.rstrip("\n").split("\t")
            rec = read_target(reader, cols[0], cols[1], cols[2:], a.private_dir, follow_links=not a.no_follow)
            out.write(json.dumps(rec, ensure_ascii=False) + "\n")
            out.flush()
            ok = sum(1 for pg in rec["pages"] if pg.get("status") == 200)
            print(f"{cols[0]}: {ok}/{len(rec['pages'])} pages 200; robots {list(rec['robots'].values())}", file=sys.stderr)


if __name__ == "__main__":
    main()
