# ---------------------------------------------------------------- robots.txt matching (RFC 9309)

# D-030: RFC 9309 §2.2.1 binds a crawler to the groups naming its own product token, else `*`. It says nothing about
# other agents' groups, so which of those bind is project policy, taken from the providers' own descriptions
# (`../../02-competitor-discovery/robots-applicability-s12.md`).
APPLICABLE_AGENT_TOKENS = ("claude-user",)
UNCERTAIN_AGENT_TOKENS = ("anthropic-ai", "claude-web")
RECORDED_AGENT_TOKENS = ("claudebot", "claude-searchbot", "chatgpt-user", "perplexity-user", "gptbot", "oai-searchbot",
                         "perplexitybot", "ccbot", "google-extended", "bytespider", "amazonbot", "applebot-extended",
                         "meta-externalagent", "cohere-ai", "exauser", "exasearchbot")
SIGNAL_KEYS = ("search", "ai-input", "ai-train")
APPLICABLE_SIGNAL = "ai-input"
USE_VALUES = ("immediate", "reference", "full")  # Cloudflare content-use extension (testing): what may be kept / reused
USE_BLOCKING = ("immediate",)  # "store and reuse nothing": research cannot keep even facts, so it is an opt-out here
# Cloudflare's managed robots.txt (Bot Preference Sync) writes one labelled section per site policy it enforces. A
# legacy-token group inside the "Training crawlers" section was generated by the site's Training = Disallow policy, so
# its purpose is documented: a training opt-out, not binding for non-training retrieval. An Agent section expresses a
# category-level block of user-directed AI agents and binds us even if our token is not listed.
MANAGED_BEGIN = re.compile(r"BEGIN Cloudflare Managed content", re.I)
MANAGED_END = re.compile(r"END Cloudflare Managed content", re.I)
TRAINING_SECTION = re.compile(r"training", re.I)
AGENT_SECTION = re.compile(r"\bagents?\b|user[- ]initiated|assistants?", re.I)
_UNRESERVED = frozenset("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~")
_HEX2 = re.compile(rb"[0-9A-Fa-f]{2}")


def normalize(value, pattern=False):
    """Percent-encoding normalisation before comparison (RFC 9309 §2.2.2, RFC 3986 §6.2.2): octets outside printable
    US-ASCII are percent-encoded, escapes of unreserved characters are decoded, other escapes use upper-case hex.
    In a URL path a literal `*` or `$` is encoded (%2A / %24) so only a rule's own `*` / trailing `$` act as syntax."""
    raw, out, i = value.encode("utf-8"), [], 0
    while i < len(raw):
        c = raw[i]
        if c == 0x25 and _HEX2.fullmatch(raw[i + 1:i + 3]):
            decoded = chr(int(raw[i + 1:i + 3], 16))
            out.append(decoded if decoded in _UNRESERVED else "%" + raw[i + 1:i + 3].decode().upper())
            i += 3
            continue
        if c <= 0x20 or c >= 0x7F or (not pattern and chr(c) in "*$"):
            out.append("%%%02X" % c)
        else:
            out.append(chr(c))
        i += 1
    return "".join(out)


def parse_signal(value):
    """`Content-Signal` value -> (path prefix or None, {key: allowed}). Accepts `ai-train=no, search=yes` and the
    path-scoped form `/blog/ ai-train=no, ...`; unknown keys and values other than yes / no are ignored."""
    value, prefix = value.strip(), None
    if value.startswith("/"):
        prefix, _, value = value.partition(" ")
    signals = {}
    for part in value.split(","):
        key, sep, val = (s.strip().lower() for s in part.partition("="))
        if sep and key in SIGNAL_KEYS and val in ("yes", "no"):
            signals[key] = val == "yes"
        elif sep and key == "use" and val in USE_VALUES:
            signals["use"] = val
    return prefix, signals


def parse_groups(robots_text):
    """Groups of (agent product tokens, [(allow, pattern)], [(prefix, signals)], managed section label or None).
    Consecutive user-agent lines share one group; rules before the first user-agent line belong to no group; other keys
    (sitemap, crawl-delay, content-signal) do not end a group. Comments never affect matching; they only label groups
    inside a `# BEGIN / END Cloudflare Managed content` block with the section comment above them."""
    groups, current, managed, section = [], None, False, None
    for raw in robots_text.splitlines():
        stripped = raw.strip()
        if stripped.startswith("#"):
            note = stripped.lstrip("#").strip()
            if MANAGED_BEGIN.search(note):
                managed, section = True, ""
            elif MANAGED_END.search(note):
                managed, section = False, None
            elif managed and note:
                section = note
            continue
        line = raw.split("#", 1)[0].strip()
        if ":" not in line:
            continue
        key, val = (s.strip() for s in line.split(":", 1))
        key = key.lower()
        if key == "user-agent":
            if current is None or current[1]:
                current = ([], [], [], section if managed else None)
                groups.append(current)
            token = re.match(r"[A-Za-z_*\-]+", val)
            current[0].append(token.group(0).lower() if token else val.lower())
        elif key in ("allow", "disallow") and current is not None:
            current[1].append((key == "allow", val))
        elif key == "content-signal" and current is not None:
            prefix, signals = parse_signal(val)
            if signals:
                current[2].append((prefix, signals))
    return groups


def rules_for(groups, token, keep=lambda group: True):
    """Every non-empty rule of every group naming `token` (RFC 9309 §2.2.1: matching groups are combined); `keep`
    narrows the groups considered (D-030 leaves out documented training sections for the legacy tokens)."""
    return [rule for g in groups if token in g[0] and keep(g) for rule in g[1] if rule[1]]


def in_training_section(group):
    return bool(group[3]) and bool(TRAINING_SECTION.search(group[3]))


def in_agent_section(group):
    return bool(group[3]) and bool(AGENT_SECTION.search(group[3])) and not in_training_section(group)


def content_signals(groups, path, tokens=("*",) + APPLICABLE_AGENT_TOKENS):
    """Signals that apply to `path` from the groups naming `tokens`; per key the longest matching prefix wins and an
    unscoped signal counts as prefix ''. A missing key neither grants nor restricts (contentsignals.org)."""
    best = {}
    for group in groups:
        if not any(t in group[0] for t in tokens):
            continue
        for prefix, values in group[2]:
            scope = prefix or ""
            if not path.startswith(scope):
                continue
            for key, allowed in values.items():
                if key not in best or len(scope) >= best[key][0]:
                    best[key] = (len(scope), allowed)
    return {key: allowed for key, (_, allowed) in best.items()}


def _pattern_regex(pattern):
    anchored = pattern.endswith("$")
    body = normalize(pattern[:-1] if anchored else pattern, pattern=True).replace("$", "%24")
    return re.compile("^" + ".*".join(re.escape(part) for part in body.split("*")) + ("$" if anchored else ""), re.S)


def match_rules(rules, path):
    """(allowed, matching rule or None). The most specific (longest) matching pattern wins; a tie goes to Allow."""
    if urllib.parse.urlsplit(path).path == "/robots.txt":
        return True, None
    target, best = normalize(path), None
    for allow, pattern in rules:
        if _pattern_regex(pattern).match(target):
            key = (len(normalize(pattern, pattern=True)), allow)
            if best is None or key > best[0]:
                best = (key, (allow, pattern))
    return (True, None) if best is None else (best[1][0], best[1])


def robots_allows(robots_text, path):
    """Verdict for our generic browser User-Agent: only `*` groups apply (same policy as _tools/capture/robots.mjs)."""
    return match_rules(rules_for(parse_groups(robots_text), "*"), path)


def agent_policy(robots_text, path):
    """D-030 classification for `path` (path + query): which AI-agent groups disallow it and how each one counts.
    Returns {"applicable": [...], "uncertain": [...], "recorded": [...], "signals": {key: allowed}}; an applicable
    `ai-input=no` signal appears in "applicable" as "content-signal:ai-input=no"."""
    groups = parse_groups(robots_text)

    def disallowed(rules):
        return bool(rules) and not match_rules(rules, path)[0]

    signals = content_signals(groups, path)
    applicable = [t for t in APPLICABLE_AGENT_TOKENS if disallowed(rules_for(groups, t))]
    if signals.get(APPLICABLE_SIGNAL) is False:
        applicable.append(f"content-signal:{APPLICABLE_SIGNAL}=no")
    if signals.get("use") in USE_BLOCKING:
        applicable.append(f"content-signal:use={signals['use']}")
    if any(in_agent_section(g) and disallowed([r for r in g[1] if r[1]]) for g in groups):
        applicable.append("cloudflare-managed:agent-policy")
    uncertain, recorded = [], [t for t in RECORDED_AGENT_TOKENS if disallowed(rules_for(groups, t))]
    for token in UNCERTAIN_AGENT_TOKENS:
        if disallowed(rules_for(groups, token, keep=lambda g: not in_training_section(g))):
            uncertain.append(token)
        elif disallowed(rules_for(groups, token)):
            recorded.append(f"{token} (managed training section)")
    return {"applicable": sorted(applicable), "uncertain": sorted(uncertain), "recorded": sorted(recorded),
            "signals": signals}


def ai_agent_optout(robots_text, path):
    """Tokens / signals that stop a read under D-030 (applicable + uncertain). Empty list = no AI-agent restriction."""
    policy = agent_policy(robots_text, path)
    return sorted(policy["applicable"] + policy["uncertain"])


# ---------------------------------------------------------------- transport, pacing, redirects

class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """Hand every 3xx back to the caller (urllib raises it as HTTPError) instead of fetching the destination."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class HttpTransport:
    """One plain GET, never following redirects. Returns (status or None, lower-cased headers, body bytes)."""

    def __init__(self, accept_encoding=None):
        self.opener = urllib.request.build_opener(_NoRedirect)
        self.accept_encoding = accept_encoding

    @staticmethod
    def decode_body(headers, body):
        """Undo gzip / deflate transfer coding; a server may compress even when the request did not ask for it."""
        coding = headers.get("content-encoding", "").lower()
        try:
            if "gzip" in coding:
                return zlib.decompress(body, zlib.MAX_WBITS | 16)
            if "deflate" in coding:
                return zlib.decompress(body)
        except zlib.error:
            return body
        return body

    def get(self, url):
        headers = {"User-Agent": UA, "Accept-Language": "id-ID,id;q=0.9,en;q=0.8", "Accept": "text/html,application/xhtml+xml"}
        if self.accept_encoding:
            headers["Accept-Encoding"] = self.accept_encoding
        req = urllib.request.Request(url, headers=headers)
        try:
            with self.opener.open(req, timeout=25) as resp:
                hdrs = {k.lower(): v for k, v in resp.headers.items()}
                return resp.status, hdrs, self.decode_body(hdrs, resp.read(MAX_BYTES))
        except urllib.error.HTTPError as e:
            headers = {k.lower(): v for k, v in e.headers.items()} if e.headers else {}
            return e.code, headers, (e.read(200_000) if e.fp else b"")
        except Exception as e:  # network error, TLS error, timeout
            return None, {}, repr(e).encode()[:300]


class Origin:
    """Per-origin state: robots verdict and text, last request time, stop reason."""

    def __init__(self, origin):
        self.origin, self.last, self.stopped = origin, None, None
        self.robots, self.robots_text = None, None
        self.recorded = []  # AI-agent groups that disallow a requested path but do not bind these reads (D-030)


class Reader:
    """All network access of this tool. `transport`, `clock` and `sleep` are injectable for the offline tests."""

    def __init__(self, transport, clock=time.monotonic, sleep=time.sleep, spacing=SPACING_S):
        self.transport, self.clock, self.sleep, self.spacing = transport, clock, sleep, spacing
        self.origins = {}
        self.requests = []  # every URL actually requested, in order

    def state(self, origin):
        return self.origins.setdefault(origin, Origin(origin))

    def _request(self, url):
        st = self.state(origin_of(url))
        if st.last is not None:
            gap = self.clock() - st.last
            if gap < self.spacing:
                self.sleep(self.spacing - gap)
        st.last = self.clock()
        self.requests.append(url)
        return self.transport.get(url)

    def robots(self, origin):
        """Read and classify robots.txt once per origin; rules found after redirects apply to `origin`."""
        st = self.state(origin)
        if st.robots is not None:
            return st
        url, status, headers, body = origin + "/robots.txt", None, {}, b""
        for _ in range(MAX_REDIRECTS + 1):
            status, headers, body = self._request(url)
            if status in REDIRECT_CODES and headers.get("location"):
                url = urllib.parse.urljoin(url, headers["location"])
                continue
            break
        else:
            st.robots = f"disallow-all (robots.txt unreachable: more than {MAX_REDIRECTS} redirects, D-022)"
            return st
        text = body.decode("utf-8", "replace") if isinstance(body, bytes) else ""
        if status is None or status == 429 or status >= 500 or status in REDIRECT_CODES:
            st.robots = f"disallow-all (robots.txt {status or 'unreachable'}, D-022)"
        elif 400 <= status < 500:
            st.robots = f"no rules (robots.txt {status})"
        elif "html" in headers.get("content-type", "").lower() or text.lstrip().lower().startswith(("<!doctype", "<html")):
            st.robots = "no rules (robots.txt answered HTML)"
        else:
            st.robots, st.robots_text = f"rules (robots.txt {status}, {len(text.splitlines())} lines)", text
        return st

    def verdict(self, url):
        """(allowed, reason). Reads robots.txt of the URL's origin first; an AI-agent opt-out stops the origin."""
        st = self.robots(origin_of(url))
        if st.robots.startswith("disallow-all"):
            return False, f"robots.txt: {st.robots}"
        if st.robots_text:
            path = path_with_query(url)
            policy = agent_policy(st.robots_text, path)
            st.recorded = sorted(set(st.recorded) | set(policy["recorded"]))
            if policy["applicable"]:
                st.stopped = f"robots.txt AI-agent opt-out ({', '.join(policy['applicable'])}; applicable, D-030)"
                return False, st.stopped
            if policy["uncertain"]:
                st.stopped = (f"robots.txt legacy Anthropic group ({', '.join(policy['uncertain'])}) disallows the path; "
                              "applicability undocumented, restriction kept (D-030, Q-O08)")
                return False, st.stopped
            ok, rule = robots_allows(st.robots_text, path)
            if not ok:
                return False, f"robots.txt disallows ({'Allow' if rule[0] else 'Disallow'}: {rule[1]})"
        return True, None

    def get(self, url):
        """Read one page. Redirects are followed by hand, each hop checked like a first request.

        Returns a dict: url, status, final_url, content_type, body (bytes or None), hops, and `skipped` or `error`
        or `blocked` when the read did not complete."""
        result, current = {"url": url, "hops": []}, url
        for hop in range(MAX_REDIRECTS + 1):
            st = self.state(origin_of(current))
            if st.stopped:
                result["skipped"] = f"origin stopped: {st.stopped}"
                return result
            if hop and NEVER_REACH.search(path_with_query(current)):
                result["skipped"] = f"redirect to a never-reach page (D-008 / auth / commerce): {path_with_query(current)}"
                return result
            ok, reason = self.verdict(current)
            if not ok:
                result["skipped"] = reason + (f" at redirect target {current}" if hop else "")
                return result
            status, headers, body = self._request(current)
            if status in REDIRECT_CODES and headers.get("location"):
                target = urllib.parse.urljoin(current, headers["location"])
                result["hops"].append({"url": current, "status": status, "location": target})
                current = target
                continue
            result.update(status=status, final_url=current, content_type=headers.get("content-type", ""),
                          body=body if isinstance(body, bytes) else b"")
            if status is None:
                result["error"] = result.pop("body").decode("utf-8", "replace")[:200]
            elif status in (401, 403, 429, 503) or (status == 200 and len(body) < 60000 and
                                                     CHALLENGE.search(body[:20000].decode("utf-8", "replace"))):
                st.stopped = f"HTTP {status} / challenge at {current}"
                result["blocked"] = "challenge or access block: no further requests to this origin, no fallback"
            return result
        result["skipped"] = f"more than {MAX_REDIRECTS} redirects: not followed"
        return result


