import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { solidPng } from './files';
import { LOCALES, manifestSchema, NICHES, TIERS, type Manifest } from './schema';

/**
 * `harness new`: the smallest template that passes every gate (system fonts, motion level 0, generated OG image), so an
 * author starts from green and every later failure is something they added.
 */
export function scaffoldTemplate(dir: string, options: { tier?: string; niche?: string; locales?: string[] } = {}) {
  const tier = (options.tier ?? 'basic') as Manifest['tier'];
  const niche = (options.niche ?? 'wedding') as Manifest['niche'];
  const locales = (options.locales?.length ? options.locales : ['id']) as Manifest['locales'];
  if (!TIERS.includes(tier)) throw new Error(`--tier must be one of ${TIERS.join(', ')}`);
  if (!NICHES.includes(niche)) throw new Error(`--niche must be one of ${NICHES.join(', ')}`);
  if (!locales.every((locale) => (LOCALES as readonly string[]).includes(locale))) throw new Error(`--locale must be ${LOCALES.join(' and/or ')}`);
  if (existsSync(join(dir, 'template.manifest.json'))) throw new Error(`${dir} already holds a template`);

  mkdirSync(join(dir, 'assets'), { recursive: true });
  const og = solidPng(1200, 630, [246, 242, 236]);
  writeFileSync(join(dir, 'assets/og.png'), og);
  const id = basename(resolve(dir)).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'new-template';
  const text = (idText: string, enText: string) => Object.fromEntries(locales.map((locale) => [locale, locale === 'id' ? idText : enText]));
  const manifest: Manifest = {
    schemaVersion: 1,
    id,
    name: id,
    version: '0.1.0',
    niche,
    tier,
    locales,
    defaultLocale: locales[0],
    sections: [
      { id: 'cover', required: true, slots: [{ key: 'guest.name', kind: 'text', maxLength: 150 }] },
      { id: 'events', required: true, slots: [{ key: 'event.title', kind: 'text' }, { key: 'event.time', kind: 'datetime' }] },
    ],
    tokens: {
      colors: { background: '#f6f2ec', surface: '#ffffff', text: '#2b2724', mutedText: '#5f5750', accent: '#8a5a2b', onAccent: '#ffffff' },
      typography: { display: 'system-serif', body: 'system-sans' },
      radius: '12px',
      spacingScale: [4, 8, 16, 24, 40],
    },
    motion: { level: 0, durationsMs: [], easing: 'ease', reducedMotion: 'none' },
    assets: [{ id: 'og', path: 'assets/og.png', kind: 'og', bytes: og.length, width: 1200, height: 630, license: 'own-work', source: 'generated by harness new', author: 'Invitesion', provenance: 'generated', deferred: false }],
    personalization: { guestName: { slot: 'guest.name', maxLength: 150, dir: 'auto' }, allowedSources: ['guests-table'] },
    accessibility: { minContrast: { body: 4.5, large: 3 }, lang: locales[0], focusVisible: true },
    strings: { invite: text('Kepada Yth.', 'Dear'), events: text('Acara', 'Events') },
    originality: { statement: 'Scaffold produced by the harness; replace with the template author’s own statement.', references: [] },
    og: { asset: 'og' },
    externalScripts: [],
  };
  manifestSchema.parse(manifest);
  writeFileSync(join(dir, 'template.manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(
    join(dir, 'template.html'),
    '<main class="page">\n  <header class="cover">\n    <p>{{t.invite}}</p>\n    <p class="guest"><bdi>{{guest.name}}</bdi></p>\n  </header>\n  <section class="events">\n    <h2>{{t.events}}</h2>\n    {{#events}}<article><h3>{{event.title}}</h3><p>{{event.time}}</p></article>{{/events}}\n  </section>\n</main>\n',
  );
  writeFileSync(
    join(dir, 'template.css'),
    'body{margin:0;background:var(--color-background);color:var(--color-text);font-family:var(--font-body)}\n.page{max-width:36rem;margin:0 auto;padding:var(--space-3)}\nh2,h3,.guest{font-family:var(--font-display)}\n',
  );
  return manifest;
}
